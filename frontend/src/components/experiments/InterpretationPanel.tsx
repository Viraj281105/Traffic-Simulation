import { useState } from "react";
import { Sparkles } from "lucide-react";
import { interpret, type Interpretation } from "../../services/v3/copilot";
import { ExperimentsApiError } from "../../services/v3/experiments";

/** Reading of a finished experiment by the Copilot.
 *
 *  The template summary is built by the server from the measured result. A
 *  model-written interpretation, when the server has a model and the text
 *  passes the grounding check, is shown below it in its own clearly labelled
 *  box; the measured tables above stay the evidence. */
export function InterpretationPanel({
  experimentId,
  alternatives,
}: {
  experimentId: string;
  alternatives: { id: string; label: string }[];
}) {
  const [preferred, setPreferred] = useState<string>("");
  const [reading, setReading] = useState<Interpretation | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const run = () => {
    setBusy(true);
    setError(null);
    interpret(experimentId, preferred || null)
      .then(setReading)
      .catch((err: unknown) => {
        setError(
          err instanceof ExperimentsApiError
            ? err.message
            : "The interpretation could not be produced.",
        );
      })
      .finally(() => {
        setBusy(false);
      });
  };

  return (
    <section className="experiment-block" aria-labelledby="exp-interpretation">
      <h2 id="exp-interpretation">Interpretation</h2>
      <p className="experiment-muted">
        A plain-language reading of the measured results above. It is built from
        those results only; if you name the alternative you hope wins, every
        finding against it is listed.
      </p>
      <div className="interpretation-controls">
        <label>
          Preferred alternative{" "}
          <select
            value={preferred}
            onChange={(e) => {
              setPreferred(e.target.value);
            }}
          >
            <option value="">None</option>
            {alternatives.map((a) => (
              <option key={a.id} value={a.id}>
                {a.label}
              </option>
            ))}
          </select>
        </label>
        <button
          type="button"
          className="pb-btn pb-secondary"
          onClick={run}
          disabled={busy}
        >
          <Sparkles size={15} aria-hidden="true" />
          {busy ? "Reading…" : "Explain the results"}
        </button>
      </div>
      {error ? (
        <p className="experiment-error" role="alert">
          {error}
        </p>
      ) : null}
      {reading ? (
        <>
          <h3>Summary of the measured results</h3>
          <pre className="interpretation-text">{reading.template}</pre>
          {reading.interpretation ? (
            <div className="interpretation-generated">
              <p className="uf-badge">{reading.interpretation.label}</p>
              <pre className="interpretation-text">
                {reading.interpretation.text}
              </pre>
              <p className="experiment-muted">
                Generated by a language model from the evidence above; every
                number in it was checked against the measured results. The
                tables remain the evidence.
              </p>
            </div>
          ) : (
            <p className="experiment-muted">
              AI assistance unavailable
              {reading.aiUnavailableReason
                ? `: ${reading.aiUnavailableReason}.`
                : "."}{" "}
              The summary above is built from the measured results only.
            </p>
          )}
        </>
      ) : null}
    </section>
  );
}
