#!/usr/bin/env python3
"""Generate a typed TypeScript fetch client from the v3 OpenAPI snapshot.

    python scripts/generate_ts_client.py [--snapshot PATH] [--out PATH]

Reads ``shared/schemas/v3/openapi.v3.snapshot.json`` (never edits it) and
writes ``clients/typescript/urbanflow.ts`` by default: one TypeScript type per
``components.schemas`` entry and one exported function per operation. The
output is deterministic (sorted, no timestamps, LF endings), so it can be
checked in and diffed. Standard library only.

Conventions of the generated client:
* every function is ``name(cfg, args?)``; ``cfg`` carries ``baseUrl``,
  ``token`` (Authorization: Bearer) and ``apiKey`` (X-API-Key), so the
  ``authorization`` / ``x-api-key`` header parameters are not repeated per call;
* ``args`` holds ``path``, ``query``, ``header`` (other headers) and ``body``;
* non-2xx responses throw ``ApiError`` with the status and parsed body.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SNAPSHOT = ROOT / "shared" / "schemas" / "v3" / "openapi.v3.snapshot.json"
DEFAULT_OUT = ROOT / "clients" / "typescript" / "urbanflow.ts"

METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
AUTH_HEADERS = {"authorization", "x-api-key"}
RESERVED = frozenset(
    "break case catch class const continue debugger default delete do else enum "
    "export extends false finally for function if import in instanceof new null "
    "return super switch this throw true try typeof var void while with yield "
    "let static implements interface package private protected public await async "
    "request buildUrl operations".split()
)
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")

PREAMBLE = """\
// Generated by scripts/generate_ts_client.py from {snapshot}. Do not edit.

export interface ClientConfig {{
  baseUrl: string;
  token?: string;
  apiKey?: string;
  headers?: Record<string, string>;
  fetch?: typeof fetch;
}}

export class ApiError extends Error {{
  constructor(
    public readonly status: number,
    public readonly body: unknown,
  ) {{
    super(`HTTP ${{status}}`);
    this.name = "ApiError";
  }}
}}

type Primitive = string | number | boolean;

function buildUrl(
  cfg: ClientConfig,
  path: string,
  query?: Record<string, Primitive | Primitive[] | null | undefined>,
): string {{
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query ?? {{}})) {{
    if (value === undefined || value === null) continue;
    for (const item of Array.isArray(value) ? value : [value]) {{
      params.append(key, String(item));
    }}
  }}
  const qs = params.toString();
  return cfg.baseUrl.replace(/\\/+$/, "") + path + (qs ? `?${{qs}}` : "");
}}

async function request(
  cfg: ClientConfig,
  method: string,
  path: string,
  opts: {{
    query?: Record<string, Primitive | Primitive[] | null | undefined>;
    header?: Record<string, string | undefined>;
    body?: unknown;
    bodyKind?: "json" | "form" | "binary";
    response?: "json" | "blob" | "none";
  }} = {{}},
): Promise<unknown> {{
  const headers: Record<string, string> = {{ ...(cfg.headers ?? {{}}) }};
  if (cfg.token) headers["Authorization"] = `Bearer ${{cfg.token}}`;
  if (cfg.apiKey) headers["X-API-Key"] = cfg.apiKey;
  for (const [key, value] of Object.entries(opts.header ?? {{}})) {{
    if (value !== undefined) headers[key] = value;
  }}
  let body: BodyInit | undefined;
  if (opts.body !== undefined) {{
    if (opts.bodyKind === "json") {{
      headers["Content-Type"] = "application/json";
      body = JSON.stringify(opts.body);
    }} else {{
      body = opts.body as BodyInit;
    }}
  }}
  const doFetch = cfg.fetch ?? fetch;
  const res = await doFetch(buildUrl(cfg, path, opts.query), {{ method, headers, body }});
  if (!res.ok) {{
    const text = await res.text();
    let parsed: unknown = text;
    try {{
      parsed = JSON.parse(text);
    }} catch {{
      /* keep the raw text */
    }}
    throw new ApiError(res.status, parsed);
  }}
  if (opts.response === "none" || res.status === 204) return undefined;
  if (opts.response === "blob") return res.blob();
  return res.json();
}}
"""


def ts_key(name: str) -> str:
    return name if _IDENT.match(name) else json.dumps(name)


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_$]", "_", name)
    return cleaned if re.match(r"[A-Za-z_$]", cleaned) else "_" + cleaned


def ts_type(schema: Any, indent: int = 0) -> str:
    """The TypeScript type of a JSON-schema fragment."""
    if not isinstance(schema, dict) or not schema:
        return "unknown"
    if "$ref" in schema:
        return type_name(ref_name(schema["$ref"]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"]) or "never"
    for combiner, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if combiner in schema:
            parts = [ts_type(s, indent) for s in schema[combiner]]
            # keep a stable order, drop repeats
            seen: List[str] = []
            for p in parts:
                if p not in seen:
                    seen.append(p)
            return joiner.join(
                f"({p})" if " | " in p and joiner == " & " else p for p in seen
            )
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": k}, indent) for k in kind)
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" else "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        item = ts_type(schema.get("items"), indent)
        return f"({item})[]" if re.search(r"[|&]", item) else f"{item}[]"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        return object_type(schema, indent)
    return "unknown"


def object_type(schema: Dict[str, Any], indent: int) -> str:
    props: Dict[str, Any] = schema.get("properties") or {}
    required: Set[str] = set(schema.get("required") or [])
    extra = schema.get("additionalProperties")
    pad = "  " * (indent + 1)
    lines: List[str] = []
    for name in sorted(props):
        optional = "" if name in required else "?"
        lines.append(
            f"{pad}{ts_key(name)}{optional}: {ts_type(props[name], indent + 1)};"
        )
    if extra is True:
        lines.append(f"{pad}[key: string]: unknown;")
    elif isinstance(extra, dict) and extra:
        lines.append(f"{pad}[key: string]: {ts_type(extra, indent + 1)};")
    if not lines:
        return "Record<string, unknown>"
    return "{\n" + "\n".join(lines) + "\n" + "  " * indent + "}"


def camel(snake: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", snake) if p]
    if not parts:
        return "operation"
    head, tail = parts[0], parts[1:]
    out = head[0].lower() + head[1:] + "".join(p[0].upper() + p[1:] for p in tail)
    return out if re.match(r"[A-Za-z_$]", out) else "_" + out


def short_operation_name(op_id: str, path: str, method: str) -> str:
    """FastAPI ids are '<function>_<path slug>_<method>'; keep the function."""
    suffix = re.sub(r"\W", "_", path) + "_" + method
    if op_id.endswith(suffix) and len(op_id) > len(suffix):
        return op_id[: -len(suffix)]
    return op_id


def collect_operations(spec: Dict[str, Any]) -> List[Dict[str, Any]]:
    raw: List[Tuple[str, str, Dict[str, Any], List[Any]]] = []
    for path in sorted(spec.get("paths", {})):
        item = spec["paths"][path]
        for method in METHODS:
            if method in item:
                raw.append((path, method, item[method], item.get("parameters", [])))
    short: Dict[str, int] = {}
    for path, method, op, _ in raw:
        name = short_operation_name(
            op.get("operationId") or f"{method}_{path}", path, method
        )
        short[camel(name)] = short.get(camel(name), 0) + 1
    ops: List[Dict[str, Any]] = []
    used: Set[str] = set()
    for path, method, op, shared in raw:
        op_id = op.get("operationId") or method + re.sub(r"\W", "_", path)
        name = camel(short_operation_name(op_id, path, method))
        if short.get(name, 0) > 1 or name in used or name in RESERVED:
            name = camel(op_id)
        used.add(name)
        ops.append(
            {
                "name": name,
                "operationId": op_id,
                "method": method,
                "path": path,
                "op": op,
                "parameters": list(shared) + list(op.get("parameters", [])),
            }
        )
    return ops


def success_response(op: Dict[str, Any]) -> Tuple[str, str]:
    """(TypeScript type, response mode) of the lowest 2xx response."""
    codes = sorted(c for c in op.get("responses", {}) if re.fullmatch(r"2\d\d", c))
    if not codes:
        return "unknown", "json"
    content = op["responses"][codes[0]].get("content") or {}
    if not content:
        return "void", "none"
    if "application/json" in content:
        return ts_type(content["application/json"].get("schema")), "json"
    return "Blob", "blob"


def render_operation(ctx: Dict[str, Any], spec: Dict[str, Any]) -> str:
    name, method, path, op = ctx["name"], ctx["method"], ctx["path"], ctx["op"]
    params = [
        p
        for p in ctx["parameters"]
        if not (p["in"] == "header" and p["name"].lower() in AUTH_HEADERS)
    ]
    groups: Dict[str, List[Dict[str, Any]]] = {"path": [], "query": [], "header": []}
    for p in params:
        if p["in"] in groups:
            groups[p["in"]].append(p)

    fields: List[str] = []
    required_any = False
    for place in ("path", "query", "header"):
        items = sorted(groups[place], key=lambda p: p["name"])
        if not items:
            continue
        inner = "; ".join(
            f"{ts_key(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p.get('schema'), 0)}"
            for p in items
        )
        needed = any(p.get("required") for p in items)
        required_any = required_any or needed
        fields.append(f"{place}{'' if needed else '?'}: {{ {inner} }}")

    body = op.get("requestBody")
    body_kind = ""
    if body:
        content = body.get("content", {})
        if "application/json" in content:
            body_kind, body_ts = (
                "json",
                ts_type(content["application/json"].get("schema")),
            )
        elif "multipart/form-data" in content:
            body_kind, body_ts = "form", "FormData"
        else:
            body_kind, body_ts = "binary", "Blob | ArrayBuffer | Uint8Array | string"
        needed = bool(body.get("required"))
        required_any = required_any or needed
        fields.append(f"body{'' if needed else '?'}: {body_ts}")

    result_ts, mode = success_response(op)
    summary = (op.get("summary") or op.get("description") or "").strip().splitlines()
    doc = (
        f"/** {method.upper()} {path}" + (f" - {summary[0]}" if summary else "") + " */"
    )
    arg_type = "{ " + "; ".join(fields) + " }"
    sig = (
        f"cfg: ClientConfig, args: {arg_type}"
        if required_any
        else f"cfg: ClientConfig, args: {arg_type} = {{}}"
    )
    if not fields:
        sig = "cfg: ClientConfig"

    url = path
    for p in groups["path"]:
        url = url.replace(
            "{" + p["name"] + "}",
            "${encodeURIComponent(String(args.path." + p["name"] + "))}",
        )
    path_expr = f"`{url}`" if "${" in url else json.dumps(url)
    opts: List[str] = []
    if groups["query"]:
        opts.append("query: args.query")
    if groups["header"]:
        opts.append("header: args.header")
    if body:
        opts.append("body: args.body")
        opts.append(f'bodyKind: "{body_kind}"')
    opts.append(f'response: "{mode}"')
    cast = "" if result_ts == "void" else f" as {result_ts}"
    ret = "Promise<void>" if result_ts == "void" else f"Promise<{result_ts}>"
    call = (
        f'await request(cfg, "{method.upper()}", {path_expr}, {{ {", ".join(opts)} }})'
    )
    lines = [doc, f"export async function {name}({sig}): {ret} {{"]
    if result_ts == "void":
        lines.append(f"  {call};")
    else:
        lines.append(f"  return ({call}){cast};")
    lines.append("}")
    return "\n".join(lines)


def generate(spec: Dict[str, Any], snapshot_label: str) -> str:
    out: List[str] = [PREAMBLE.format(snapshot=snapshot_label), ""]
    schemas = spec.get("components", {}).get("schemas", {})
    out.append("// ---- Types (components.schemas) ----")
    for name in sorted(schemas):
        schema = schemas[name]
        tn = type_name(name)
        if (
            schema.get("type") == "object"
            and "properties" in schema
            and not schema.get("enum")
        ):
            out.append(f"export interface {tn} {object_type(schema, 0)}")
        else:
            out.append(f"export type {tn} = {ts_type(schema)};")
        out.append("")
    ops = collect_operations(spec)
    out.append("// ---- Operations ----")
    out.append("export const operations = [")
    for ctx in ops:
        out.append(
            "  { "
            f'name: "{ctx["name"]}", operationId: {json.dumps(ctx["operationId"])}, '
            f'method: "{ctx["method"].upper()}", path: {json.dumps(ctx["path"])} '
            "},"
        )
    out.append("] as const;")
    out.append("")
    for ctx in ops:
        out.append(render_operation(ctx, spec))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--snapshot", type=Path, default=DEFAULT_SNAPSHOT)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    spec = json.loads(args.snapshot.read_text(encoding="utf-8"))
    text = generate(spec, args.snapshot.name)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {args.out} ({len(collect_operations(spec))} operations)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
